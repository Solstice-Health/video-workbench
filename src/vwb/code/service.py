"""Private per-workspace supervisor. No project code executes on the host."""
from __future__ import annotations

import json
import os
import re
import selectors
import shutil
import signal
import socket
import subprocess
import sys
import threading
import time
import uuid
from pathlib import Path

from .fence import HostFence
from .runtime import (
    IMAGE,
    MAX_FRAME,
    OPERATIONS,
    CodeServiceError,
    clean_environment,
    image_status,
    receive_frame,
    send_frame,
)

IDLE_SECONDS = 300
LIFETIME_SECONDS = 3600
CALL_TIMEOUT = 38


def docker_command(workspace: Path, name: str) -> list[str]:
    # No caller-supplied command, image, mount, environment, or network option.
    # Mount source separately from the workspace; Python -I ignores PYTHONPATH,
    # cwd and user site packages so workspace modules cannot shadow the worker.
    source = Path(__file__).resolve().parent
    bootstrap = "import sys;sys.path.insert(0,'/run');from vwb_code.worker import main;main()"
    return [shutil.which("docker") or "docker", "run", "--rm", "--init", "-i", "--name", name,
            "--label", "vwb.code-tools=1", "--network=none", "--read-only", "--cap-drop=ALL",
            "--security-opt=no-new-privileges", "--pids-limit=128", "--memory=2048m", "--cpus=2",
            "--user=1001:1001", "--tmpfs=/tmp:rw,nosuid,nodev,size=256m,mode=1777",
            "--mount", f"type=bind,source={workspace},target=/workspace,readonly",
            "--mount", f"type=bind,source={source},target=/run/vwb_code,readonly",
            "--workdir=/workspace", "--env=HOME=/tmp", "--env=PYTHONUTF8=1", IMAGE,
            "python3", "-I", "-u", "-c", bootstrap]


class Supervisor:
    def __init__(self, workspace: Path):
        self.workspace = workspace
        self.fence = HostFence(workspace)
        self.process = None
        self.name = "vwb-code-" + uuid.uuid4().hex[:20]
        self.serial = threading.Lock()
        self.state_lock = threading.RLock()
        self.active = None
        self.cancelled: dict[str, float] = {}
        self.stop = threading.Event()
        self.last_used = time.monotonic()
        self.started = self.last_used

    def _kill(self) -> None:
        with self.state_lock:
            process, self.process = self.process, None
            if process is None:
                return
            # The name was generated by this supervisor; never kill by a caller's
            # PID, arbitrary name, workspace substring, or broad Docker filter.
            try:
                subprocess.run([shutil.which("docker") or "docker", "rm", "-f", self.name],
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                               env=clean_environment(), timeout=5, check=False)
            except (OSError, subprocess.TimeoutExpired):
                pass
            process.kill()
            try:
                process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                pass
            for stream in (process.stdin, process.stdout):
                if stream is not None:
                    stream.close()

    def cancel(self, request_id: str) -> None:
        with self.state_lock:
            now = time.monotonic()
            self.cancelled = {k: t for k, t in self.cancelled.items() if now - t < 60}
            if len(self.cancelled) < 64:
                self.cancelled[request_id] = now
            if self.active == request_id:
                self._kill()

    def call(self, request: dict) -> dict:
        request_id = request["id"]
        if not self.serial.acquire(timeout=2):
            raise CodeServiceError("Code tools are busy with another lookup. Retry shortly.")
        try:
            request, early = self.fence.prepare(request)
            if early is not None:
                return early
            with self.state_lock:
                self.last_used = time.monotonic()
                if request_id in self.cancelled or self.stop.is_set():
                    raise CodeServiceError("Code lookup was interrupted.")
                self.active = request_id
                if self.process is None or self.process.poll() is not None:
                    status = image_status()
                    if not status["ready"]:
                        raise CodeServiceError(status["message"])
                    self.process = subprocess.Popen(docker_command(self.workspace, self.name),
                        stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                        env=clean_environment(), cwd="/", bufsize=0)
                process = self.process
            data = json.dumps(request, ensure_ascii=True).encode() + b"\n"
            assert process.stdin is not None and process.stdout is not None
            output = bytearray()
            deadline = time.monotonic() + CALL_TIMEOUT
            with selectors.DefaultSelector() as selector:
                # A stalled Docker client must not block before the deadline.
                # FileIO.write may also be partial, even for a small RPC frame.
                os.set_blocking(process.stdin.fileno(), False)
                selector.register(process.stdin, selectors.EVENT_WRITE)
                sent = 0
                while sent < len(data):
                    if time.monotonic() >= deadline:
                        raise CodeServiceError("Isolated code worker did not accept the request in time.")
                    if not selector.select(timeout=0.2):
                        continue
                    try:
                        sent += os.write(process.stdin.fileno(), data[sent:])
                    except BlockingIOError:
                        continue
                selector.unregister(process.stdin)
                selector.register(process.stdout, selectors.EVENT_READ)
                while time.monotonic() < deadline:
                    if process.poll() is not None:
                        raise CodeServiceError("Isolated code worker stopped. Check Docker and retry.")
                    if not selector.select(timeout=0.2):
                        continue
                    chunk = os.read(process.stdout.fileno(), 65536)
                    if not chunk:
                        raise CodeServiceError("Isolated code worker closed its stream; retry the lookup.")
                    output.extend(chunk)
                    if len(output) > MAX_FRAME:
                        raise CodeServiceError("Isolated code result exceeded its byte bound.")
                    if b"\n" in chunk:
                        response = json.loads(output.split(b"\n", 1)[0])
                        if not isinstance(response, dict) or response.get("id") != request_id:
                            raise CodeServiceError("Isolated code worker returned a mismatched response.")
                        return self.fence.verify(request, response)
            raise CodeServiceError("Isolated code lookup timed out; narrow the query.")
        except (OSError, ValueError, CodeServiceError):
            self._kill()
            raise
        finally:
            with self.state_lock:
                self.active = None
                self.last_used = time.monotonic()
            self.serial.release()

    def handle(self, connection: socket.socket) -> None:
        request_id = None
        try:
            request = receive_frame(connection, deadline=time.monotonic() + 2)
            operation = request.get("operation")
            request_id = request.get("id")
            if operation == "ping":
                send_frame(connection, {"ready": True})
                return
            if operation == "shutdown":
                self.stop.set()
                self._kill()
                send_frame(connection, {"stopped": True})
                return
            if not isinstance(request_id, str) or not re.fullmatch("[a-f0-9]{32}", request_id):
                raise ValueError("Invalid code request identity.")
            if operation == "cancel":
                self.cancel(request_id)
                send_frame(connection, {"id": request_id, "cancelled": True})
                return
            if operation not in OPERATIONS or not isinstance(request.get("arguments", {}), dict):
                raise ValueError("Unsupported code request.")
            if len(json.dumps(request).encode()) > 65536:
                raise ValueError("Code request exceeds 64 KiB.")
            send_frame(connection, self.call(request))
        except Exception as exc:
            try:
                send_frame(connection, {"id": request_id, "error": f"{type(exc).__name__}: {str(exc)[:2000]}"})
            except OSError:
                pass
        finally:
            connection.close()

    def serve(self, path: Path) -> None:
        slots = threading.BoundedSemaphore(16)
        def handle(connection):
            try:
                self.handle(connection)
            finally:
                slots.release()
        with socket.socket(socket.AF_UNIX) as server:
            server.bind(str(path))
            os.chmod(path, 0o600)
            server.listen(16)
            server.settimeout(0.5)
            try:
                while not self.stop.is_set():
                    now = time.monotonic()
                    if self.active is None and now - self.last_used > IDLE_SECONDS:
                        break
                    if now - self.started > LIFETIME_SECONDS and self.active is None:
                        break
                    try:
                        connection, _ = server.accept()
                    except TimeoutError:
                        continue
                    if not slots.acquire(blocking=False):
                        connection.close()
                        continue
                    threading.Thread(target=handle, args=(connection,), daemon=True).start()
            finally:
                self.stop.set()
                self._kill()
                path.unlink(missing_ok=True)


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("Expected work folder and private socket.")
    workspace, path = Path(sys.argv[1]), Path(sys.argv[2])
    if workspace.is_symlink() or not workspace.is_dir():
        raise SystemExit("Expected regular work folder.")
    supervisor = Supervisor(workspace.resolve())
    # A normal server/process-manager termination still cleans up only this
    # supervisor's container. SIGKILL closes the stdio pipe; the worker also
    # exits at EOF after its bounded in-flight operation.
    def stop(_signum, _frame):
        supervisor.stop.set()
    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    supervisor.serve(path)


if __name__ == "__main__":
    main()
